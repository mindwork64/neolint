#!/usr/bin/env bash
set -euo pipefail

readonly DEFAULT_REVISION="eb8354a3984ea31123ea3f69259ed99b9edb3f05"
readonly BUILTINS_DESTINATION="data/lsl-builtins.txt"
readonly DEPRECATED_DESTINATION="data/lsl-deprecated.txt"
revision="${1:-$DEFAULT_REVISION}"

if [[ ! "$revision" =~ ^[0-9a-f]{40}$ ]]; then
  printf 'Usage: bash %s [40-character-upstream-commit-sha]\n' "$0" >&2
  exit 2
fi

readonly base_url="https://raw.githubusercontent.com/secondlife/lsl-definitions/$revision"
readonly builtins_url="$base_url/generated/builtins.txt"
readonly definitions_url="$base_url/lsl_definitions.yaml"

builtins_temporary_file="$(mktemp)"
definitions_temporary_file="$(mktemp)"
deprecated_temporary_file="$(mktemp)"
trap 'rm -f "$builtins_temporary_file" "$definitions_temporary_file" "$deprecated_temporary_file"' EXIT

curl --fail --location --silent --show-error "$builtins_url" --output "$builtins_temporary_file"
if ! grep -Fq '// Generated by gen_definitions.py' "$builtins_temporary_file"; then
  echo "Downloaded file does not look like the canonical generated LSL builtin list." >&2
  exit 1
fi

curl --fail --location --silent --show-error "$definitions_url" --output "$definitions_temporary_file"
if ! grep -Eq '^functions:
  echo "Downloaded YAML does not contain the canonical LSL functions section." >&2
  exit 1
fi

python3 scripts/extract-lsl-deprecated.py \
  "$definitions_temporary_file" "$deprecated_temporary_file" "$revision"

mkdir -p "$(dirname "$BUILTINS_DESTINATION")"
install -m 0644 "$builtins_temporary_file" "$BUILTINS_DESTINATION"
install -m 0644 "$deprecated_temporary_file" "$DEPRECATED_DESTINATION"

printf 'Updated %s and %s from secondlife/lsl-definitions@%s\n' \
  "$BUILTINS_DESTINATION" "$DEPRECATED_DESTINATION" "$revision"
 "$definitions_temporary_file"; then
  echo "Downloaded YAML does not contain the canonical LSL functions section." >&2
  exit 1
fi

python3 scripts/extract-lsl-deprecated.py \
  "$definitions_temporary_file" "$deprecated_temporary_file" "$revision"

mkdir -p "$(dirname "$BUILTINS_DESTINATION")"
install -m 0644 "$builtins_temporary_file" "$BUILTINS_DESTINATION"
install -m 0644 "$deprecated_temporary_file" "$DEPRECATED_DESTINATION"

printf 'Updated %s and %s from secondlife/lsl-definitions@%s\n' \
  "$BUILTINS_DESTINATION" "$DEPRECATED_DESTINATION" "$revision"
