#!/usr/bin/env bash
set -euo pipefail

readonly DEFAULT_REVISION="eb8354a3984ea31123ea3f69259ed99b9edb3f05"
readonly DESTINATION="data/lsl-builtins.txt"
revision="${1:-$DEFAULT_REVISION}"

if [[ ! "$revision" =~ ^[0-9a-f]{40}$ ]]; then
  printf 'Usage: bash %s [40-character-upstream-commit-sha]\n' "$0" >&2
  exit 2
fi

url="https://raw.githubusercontent.com/secondlife/lsl-definitions/$revision/generated/builtins.txt"
temporary_file="$(mktemp)"
trap 'rm -f "$temporary_file"' EXIT

curl --fail --location --silent --show-error "$url" --output "$temporary_file"

if ! grep -Fq '// Generated by gen_definitions.py' "$temporary_file"; then
  echo "Downloaded file does not look like the canonical generated LSL builtin list." >&2
  exit 1
fi

mkdir -p "$(dirname "$DESTINATION")"
install -m 0644 "$temporary_file" "$DESTINATION"
printf 'Updated %s from secondlife/lsl-definitions@%s\n' "$DESTINATION" "$revision"
